export function getItemsForSession(ageBand: AgeBand, version: "full" | "brief"): RmraItem[] {
  const items = RMRA_ITEMS.filter(item => item.ageBand === ageBand);
  if (version === "brief") return items.filter(item => item.briefVersion);
  return items;
}

export function getItemsByDomain(ageBand: AgeBand, domain: string): RmraItem[] {
  return RMRA_ITEMS.filter(item => item.ageBand === ageBand && item.domain === domain);
}

export function getItemById(id: string): RmraItem | undefined {
  return RMRA_ITEMS.find(item => item.id === id);
}
