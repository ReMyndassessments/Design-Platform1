export function chineseLiteracyStatusLabel(status: string, language: ChineseLiteracyReportLanguage) {
  const copy = CHINESE_LITERACY_DASHBOARD_PRINT_COPY[language];
  const normalized = status.toLowerCase().replaceAll("_", " ");
  const labels: Record<string, string> = {
    rated: copy.statusRated,
    "not observed": copy.statusNotObserved,
    "not applicable": copy.statusNotApplicable,
    unanswered: copy.statusUnanswered,
    submitted: copy.statusSubmitted,
    approved: copy.statusApproved,
    "under review": copy.statusUnderReview,
    "in progress": copy.statusInProgress,
    returned: copy.statusReturned,
    draft: copy.statusDraft,
    "not started": copy.statusNotStarted,
    missing: copy.statusMissing,
  };
  return labels[normalized] ?? status.replaceAll("_", " ");
}
